int EvenFactorial(int iNo)
{
     if(iNo<0)
        {
            iNo= -iNo;
           
        }
    int iFact=1;
    int iCnt =0;
    for(iCnt=1;iCnt<=iNo;iCnt++)
    {
        if((iCnt%2)==0)
        {
            iFact= iFact*iCnt;
        }  
    }  
    return iFact;
}// End of EvenFactorial

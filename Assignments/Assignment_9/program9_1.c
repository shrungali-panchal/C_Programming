void Display(int iNo)
{
    int iCnt=0;
    for(iCnt=1; iCnt<=iNo; iCnt++)
    {
        printf("*\t");
    }
    for(iCnt=1; iCnt<=iNo; iCnt++)
    {
        printf("#\t");
    }
}// End of Display
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    Display(iValue);
    return 0;
}//End of main

void Pattern(int iNo)
{
    int iCnt=0;
    if(iNo<0)
    {
        iNo = -iNo;
    }
    for(iCnt=1;iCnt<=iNo;iCnt++)
    {
        printf("$\t*\t");
    }
}// End of Pattern
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    Pattern(iValue);
    return 0;
}//End of main

//Function name:Display
//Description: It is used display number line 
//Input: Integer
//Output: Void(Displays number line of given input)
//Author:Shrungali Shrikant Panchal
//Date: 31/10/2025
//
//////////////////////////////////////////////////////////////////////////
void Display(int iNo)
{
    int iCnt=0;
    for(iCnt=-iNo;iCnt<=iNo;iCnt++)
    {
      printf("%d ", iCnt);
    }
    
}// End of Display
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    Display(iValue);
    return 0;
}//End of main

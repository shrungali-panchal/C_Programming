void OddDisplay(int iNo)
{
    int iCnt=0;
    for(iCnt=1; iCnt<iNo; iCnt++)
    if((iCnt%2)!=0)
    {
        printf("%d\t",iCnt);
    }
}// End of OddDisplay
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    OddDisplay(iValue);
    return 0;
}//End of main

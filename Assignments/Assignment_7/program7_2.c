//Function name:Display
//Description: It is used display numbers using loop
//Input: Integer
//Output: void(displays numbers till given input on console)
//Author:Shrungali Shrikant Panchal
//Date: 31/10/2025
//
//////////////////////////////////////////////////////////////////////////
void Display(int iNo)
{
    int iCnt=0;
    for(iCnt=1;iCnt<=iNo;iCnt++)
    {
      printf("%d ", iCnt);
    }
    
}// End of Display
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    Display(iValue);
    return 0;
}//End of main

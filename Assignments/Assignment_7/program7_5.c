//////////////////////////////////////////////////////////////////////////
//
//Function name:MultipleDisplay
//Description: It is used Display first five multiples of given input 
//Input: Integer
//Output: void(Displays first five multiples)
//Author:Shrungali Shrikant Panchal
//Date: 31/10/2025
//
//////////////////////////////////////////////////////////////////////////
void MultipleDisplay(int iNo)
{
    int iCnt=0;
    for(iCnt=1; iCnt<=5; iCnt++)
    {
        printf("%d\t",iNo*iCnt);
    }
}// End ofMultipleDisplay
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    MultipleDisplay(iValue);
    return 0;
}//End of main

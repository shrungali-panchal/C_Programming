int main()
{
    int iValue1=0 , iValue2=0;
    float fRet = 0.0;
    printf("Enter Total Marks:");
    scanf("%d",&iValue1);
    printf("Enter Obtained Marks:");
    scanf("%d",&iValue2);
    fRet=Percentage(iValue1,iValue2);
    printf("Percentage is:%.1f%%",fRet);
    return 0;
}//End of main

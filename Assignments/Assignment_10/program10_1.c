double CircleArea(float fNo)
{
    if(fNo<0)
    {
        fNo= - fNo;
    }
    float PI=3.14;
    float Area= PI*fNo*fNo;
    return Area;
}// End of CircleArea
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    float fValue=0;
    double dRet=0;
    printf("Enter Radius: ");
    scanf("%f",&fValue);
    dRet=CircleArea(fValue);
    printf("Area of Circle is %.4lf\n",dRet);
    return 0;
}//End of main

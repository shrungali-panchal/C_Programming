int main()
{
    int iValue=0;
    int iRet=0;
    printf("Enter Distance in Kilometer: ");
    scanf("%d",&iValue);
    iRet=KMtoMeter(iValue);
    printf("Distance in meter is %d\n",iRet);
    return 0;
}//End of main

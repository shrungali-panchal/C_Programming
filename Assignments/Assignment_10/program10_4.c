//Function name:FhtoCs
//Description: It is used to convert Fahrenheit to Celsius
//Input: Integer
//Output: Double
//Author:Shrungali Shrikant Panchal
//Date: 1/11/2025
//
//////////////////////////////////////////////////////////////////////////
double FhtoCs(float fTemp)
{
    float fCelsius=(fTemp - 32)*(5.0/9.0);
    return fCelsius; 
}// End of FhtoCs
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    float fValue=0.0;
    double dRet=0.0;
    printf("Enter Temperature in Fahrenheit: ");
    scanf("%f",&fValue);
    dRet=FhtoCs(fValue);
    printf("Temperature in celsius is %.4f\n",dRet);
    return 0;
}//End of main

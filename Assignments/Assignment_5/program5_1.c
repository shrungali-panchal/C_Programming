void CheckEvenOdd(int iNum)
{
    if(iNum<0)
    {
        iNum = -iNum;
    }
    if((iNum%2)==0)
    {
        printf("Even\n");
    }
    else
    {
        printf("Odd\n");
    }

}// End of CheckEvenOdd
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iNumber=0;
    printf("Enter number:");
    scanf("%d",&iNumber);

    CheckEvenOdd(iNumber);
    return 0;
} //End of main

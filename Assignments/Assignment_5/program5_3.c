void CheckLeapYear(int year)
{
    int leapyear = (year % 400==0) || (year % 4==0 && year % 100!=0);
    if((leapyear)==1)
    {
        printf("Leap year");
    }
    else
    {
        printf("Not a Leap year");

    }
}// End of CheckLeapYear
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int yr = 0;
    printf("Enter Year:");
    scanf("%d",&yr);
    CheckLeapYear(yr);
    return 0;
} //End of main

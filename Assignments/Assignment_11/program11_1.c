//
//////////////////////////////////////////////////////////////////////////
void RangeDisplay(int iStart,int iEnd)
{
    int iCnt=0;
    for(iCnt=iStart; iCnt<=iEnd; iCnt++)
    {
        printf("%d\t",iCnt);
    }
    
}// End of RangeDisplay
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue1=0;
    int iValue2=0;
    printf("Enter Starting point:");
    scanf("%d",&iValue1);
    printf("Enter Ending point:");
    scanf("%d",&iValue2);
    RangeDisplay(iValue1,iValue2);
    return 0;
}//End of main

void PrintEven( int iNo)
{
    if(iNo<=0)
    {
        return; 
    }
    
    int iCnt=0;
    for(iCnt=2; iCnt<iNo; iCnt++)
    if((iCnt%2)==0)
    {
        printf("%d\t",iCnt);
    }
}// End of PrintEven
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    PrintEven(iValue);
    return 0;
}  //End of main

void DisplayEvenFactors(int iNo)
{
    int i=0;
    if(iNo<=0)
    {
        iNo= -iNo;
    }
    for(i=1;i<=iNo;i++)
    {
        if((i%2==0) && (i<=iNo))
        {
            printf("%d\t",i);
        }
    }
}// End of DisplayEvenFactors

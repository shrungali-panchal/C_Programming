int Count(int iNo)
{
    int iDigit=0;
    int iCount=0;
    while(iNo!=0)
    {
        iDigit=iNo%10;
        if((iNo%10)<6)
        {
            iCount++;
        }
        iNo=iNo/10;
    }
    return iCount;
}// End of Count

int Sum_Natural_Numbers(int limit)
{
    if(limit<0)
    {
        limit = -limit;
    }
    int iSum=0;
    int i=0;
    for(i=1; i<=limit; i++)
    {
        if(limit>0)
        {
            iSum += i;
        }
    }
    return iSum;    
}// End of Sum_Natural_Numbers

void Print_Odd_Numbers(int limit)
{
    int i=0;
    for(i=1; i<=limit; i++)
    {
        if((i%2)!=0)
        {
            printf("%d\t",i);
        }
    }
}// End of Print_Odd_Numbers
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int limit=0;
    printf("Enter Number:");
    scanf("%d",&limit);
    Print_Odd_Numbers(limit);
    return 0;
}///End of main

void Display(int iNo)
{
    int iCnt = 0;
    if(iNo<0)                                           //Updater
    {
        iNo = -iNo;
    }
    while(iCnt<=iNo)
    {
        printf("*");
        iCnt++;
    }
}// End of Display 
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue = 0;                                     
    printf("Enter Number:");
    scanf("%d",&iValue);                                
    Display(iValue);                                    //Method call
    return 0;
}   //End of main

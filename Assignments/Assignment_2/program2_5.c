bool CheckEvenOdd(int iNo)
{
    int iRem=0;
    iRem = iNo % 2;

    if((iRem)==0)
    {
        return true;
    }
    else
    {
        return false;
    }
}// End of CheckEvenOdd
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    bool bRet = false;
    printf("Enter Number:");
    scanf("%d",&iValue);

    bRet=CheckEvenOdd(iValue);
    if((bRet) == true)
    {
        printf("The Number is Even",iValue);
    }
    else
    {
        printf("The Number is Odd",iValue);
    }
    return 0;
}  //End of main

int CountRange(int iNo)
{
    int iDigit=0;
    int iCount=0;
    while(iNo!=0)
    {
        iDigit=iNo%10;
        if(iDigit>=3 && iDigit<=7)
        {
            iCount++;
        }
        iNo=iNo/10;
    }
    return iCount;
}// End of CountRange
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    int iRet=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    iRet=CountRange(iValue);
    printf("%d\n",iRet);
    return 0;
}//End of main

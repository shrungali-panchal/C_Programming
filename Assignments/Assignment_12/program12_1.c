void  Print_Factors(int iNo)
{
    if(iNo<0)
    {
        iNo=  -iNo;
    }
    int i=0;
    for(i=1;i<iNo;i++)
    {
        if((iNo%i)==0)
        {
            printf("%d\t",i);  
        }
    }
}// End of  Print_Factors
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iNumber=0;
    printf("Enter Number:");
    scanf("%d",&iNumber);
    Print_Factors(iNumber);
    return 0;
}//End of main

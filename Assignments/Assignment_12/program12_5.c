bool Check_is_divisible_by_five(int iNo)
{
    if((iNo % 5)== 0)
    {
        return true;
    }
    else
    {
        return false;
    }
}// End of Check_is_divisible_by_five
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main(void)
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    
    printf("%s\n", Check_is_divisible_by_five(iValue)?"YES":"NO");
    return 0;
}//End of main

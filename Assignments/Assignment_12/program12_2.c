int  Count_Factors(int iNo)
{
    if(iNo<0)
    {
        iNo=  -iNo;
    }
    int i=0;
    int Count =0;
    for(i=1;i<=iNo;i++)
    {
        if((iNo%i)==0)
        {
            Count++; 
        }
    }
    return Count;
}// End of Count_Factors

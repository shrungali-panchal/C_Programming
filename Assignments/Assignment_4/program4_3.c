void NonFact(int iNo)
{
    if(iNo<=0)
    {
        iNo= -iNo;
    }

    int iCnt=0;
    
    for(iCnt=1; iCnt<=iNo; iCnt++)
    {
        if((iNo%iCnt) != 0)
        {
            printf("%d\t",iCnt);
            
        }
    }
}// End of NonFact
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    NonFact(iValue);
    return 0;
} //End of main

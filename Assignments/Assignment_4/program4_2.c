void FactRev(int iNo)
{
    if(iNo<=0)
    {
        iNo = -iNo;
    }
    
    int iCnt = 0;
    for(iCnt=iNo; iCnt>=1; iCnt--)
    {
        if((iNo%iCnt)==0)
        {
            printf("%d\t",iCnt);
        }
    }
}// End of FactRev
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    FactRev(iValue);
    return 0;
} //End of main

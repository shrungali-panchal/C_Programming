void Table(int iNo)
{
     if(iNo<0)                                         //Updater
        {
            iNo= -iNo;
           
        }
    int iCnt =0;
    for(iCnt=1;iCnt<=10;iCnt++)
    {
        printf("%d\t",iNo*iCnt);
    }  
}// End of Table

void Number(int iNo)
{
    if(iNo<50)
    {
        printf("Small");
    }
    else if((100>=iNo)  &&  (iNo>=50))
    {
        printf("Medium");
    }
    else if(iNo>100)
    {
        printf("Greater");
    }
}// End of Number
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    Number(iValue);
    return 0;
}//End of main

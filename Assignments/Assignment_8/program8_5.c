//Function name:TableRev
//Description: It is used Display Table in Reverse order of given input 
//Input: Integer
//Output: void(Displays Table Reverse)
//Author:Shrungali Shrikant Panchal
//Date: 1/11/2025
//
//////////////////////////////////////////////////////////////////////////
void TableRev(int iNo)
{
    if(iNo<0)                                           //Updater
    {
        iNo = -iNo;
    }
    int iCnt=0;
    for(iCnt=10; iCnt>=1; iCnt--)
    {
        printf("%d\t",iNo*iCnt);
    }
}// End of TableRev
//////////////////////////////////////////////////////////////////////////
//
//Entry point function of application
//
//////////////////////////////////////////////////////////////////////////
int main()
{
    int iValue=0;
    printf("Enter Number:");
    scanf("%d",&iValue);
    TableRev(iValue);
    return 0;
}//End of main

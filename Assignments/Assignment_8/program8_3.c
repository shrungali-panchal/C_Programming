int Factorial(int iNo)
{
     if(iNo<0)
        {
            iNo= -iNo;
           
        }
    int iFact=1;
    int iCnt =0;
    for(iCnt=1;iCnt<=iNo;iCnt++)
    {
        iFact= iFact*=iCnt;
    }  
    return iFact;
}// End of Factorial
//////////////////////////////////////////////////////////////////////////
